# Генерирует stage6/arch74_86.py из stage6/gen/t86.json (dump86.js по 1.5.25: серии из m6, цепочки из w6).
import json,os
D=os.path.dirname(os.path.abspath(__file__));T=json.load(open(os.path.join(D,'t86.json')))
ok=[s for s in T['series'] if s['ok']];assert len(ok)==4 and sum(len(s['layers'])-1 for s in ok)==6,(len(ok))
not_=[s for s in T['series'] if not s['ok']];assert len(not_)==11 and all(s['why'].startswith('слои разных подсистем') for s in not_)
kept=', '.join('%s (%s)'%(s['name'],s['why'].split(': ',1)[1]) for s in not_)
sites=[tuple(x) for x in T['sites']]
names=', '.join('%s (%d)'%(s['name'],len(s['layers'])) for s in ok)
PRE=('/* ▼▼▼ ARCH·86 · НАЧАЛО ВЫРЕЗАЕМОГО БЛОКА ▼▼▼ (1.5.26 α · этап 7: слияние серий слоёв-переустановок)\n'
     '   Исполняемого кода в этом блоке нет и флага нет. 4 серии соседних однотипных слоёв «{const _p=f; f=function(){pre; r=_p(); post; return r}}»\n'
     '   одной подсистемы (10 слоёв) заменены 4 объединёнными слоями на месте последнего слоя серии: pre — от внешнего слоя к внутреннему, post — от внутреннего\n'
     '   к внешнему, как исполнялась цепочка. Локальные имена слоёв переименованы (<имя>_86<номер слоя>), параметры внутренних слоёв читаются из\n'
     '   arguments. Серии: '+names+'.\n'
     '   Почему безопасно: между слоями серии нет других записей f, вызовов, достигающих f, и чтений f при загрузке (m6, dump86);\n'
     '   слои не меняют параметры и arguments, не возвращают раньше и не подменяют результат. Проверка — trace7 (последовательность вызовов).\n'
     '   Сливаются только серии, все слои которых принадлежат одной подсистеме. Остальные 11 серий (27 слоёв) оставлены раздельными: их слои —\n'
     '   крючки разных подсистем, на этапе 8 каждый переезжает вместе со своей подсистемой, а слияние собрало бы чужие записи G в одном месте:\n'
     '   '+kept+'.\n'
     '   Откат — снятие патча 86. */\n')
out=('# ---------- 86 · этап 7 · слияние серий слоёв ----------\n'
     '# Сгенерировано stage6/gen/gen86.py из AST 1.5.25 (dump86.js).\n'
     'PRE86=%r+END6%%86\nS86=%r\n'
     "STAGES['86']=dict(vf='1.5.25 α',vt='1.5.26 α',J='m86_journal.txt',pre=PRE86,after='85',sites=S86)\n")%(PRE,sites)
open(os.path.join(D,'..','arch74_86.py'),'w',encoding='utf8').write(out);print('ok',len(out),len(sites))
