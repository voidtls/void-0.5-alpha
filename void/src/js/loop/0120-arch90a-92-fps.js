/* ▼▼▼ ARCH·91 · НАЧАЛО ВЫРЕЗАЕМОГО БЛОКА ▼▼▼ (1.5.33 α · FPS: предел кадров не снижает качество сам по себе)
   Автокачество (qTick) и облегчённые эффекты бесконечного режима (fpsLow в frame74) судят о нехватке производительности по
   интервалу между обработанными кадрами. При пределе 30 этот интервал ≈ 1/30 с — больше прежних порогов 1/50 и 1/40, и качество
   падало без всякой нагрузки. Теперь пороги учитывают ожидаемый интервал предела E = 1/cap: снижение — при среднем > max(1/50, 1.2·E),
   fpsLow — при кадре > max(1/40, 1.2·E), повышение — при среднем < max(1/83, 1.05·E). Без предела (cap 0) и при A-27 выкл. пороги прежние.
   Настоящая перегрузка (кадр заметно дольше предела) по-прежнему снижает качество. Старый frame() не тронут. Откат — снятие патча 91. */
function qDn27(){const c=fpsCap27();return c>0?Math.max(1/50,1.2/c):1/50;}
function qUp27(){const c=fpsCap27();return c>0?Math.max(1/83,1.05/c):1/83;}
function fpsLowT27(){const c=fpsCap27();return c>0?Math.max(1/40,1.2/c):1/40;}
